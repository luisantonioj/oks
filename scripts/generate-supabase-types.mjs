import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";

const outputPath = path.resolve("types", "supabase.ts");

function loadEnvFile(filePath) {
  if (!existsSync(filePath)) return {};

  return Object.fromEntries(
    readFileSync(filePath, "utf8")
      .split(/\r?\n/)
      .map((line) => line.trim())
      .filter((line) => line && !line.startsWith("#") && line.includes("="))
      .map((line) => {
        const [key, ...valueParts] = line.split("=");
        return [key.trim(), valueParts.join("=").trim().replace(/^["']|["']$/g, "")];
      }),
  );
}

function getProjectRef() {
  const envFile = loadEnvFile(path.resolve(".env.local"));
  const explicitRef = process.env.SUPABASE_PROJECT_REF || envFile.SUPABASE_PROJECT_REF;

  if (explicitRef) return explicitRef;

  const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL || envFile.NEXT_PUBLIC_SUPABASE_URL;
  if (!supabaseUrl) return null;

  try {
    return new URL(supabaseUrl).hostname.split(".")[0] || null;
  } catch {
    return null;
  }
}

function getSupabaseCommand() {
  const localCommand = path.resolve(
    "node_modules",
    ".bin",
    process.platform === "win32" ? "supabase.cmd" : "supabase",
  );

  if (existsSync(localCommand)) {
    return { command: localCommand, argsPrefix: [] };
  }

  return {
    command: process.platform === "win32" ? "npx.cmd" : "npx",
    argsPrefix: ["--yes", "supabase"],
  };
}

const projectRef = getProjectRef();

if (!projectRef) {
  console.error(
    "Unable to determine Supabase project ref. Set SUPABASE_PROJECT_REF or NEXT_PUBLIC_SUPABASE_URL.",
  );
  process.exit(1);
}

const { command, argsPrefix } = getSupabaseCommand();
const args = [
  ...argsPrefix,
  "gen",
  "types",
  "typescript",
  "--project-id",
  projectRef,
  "--schema",
  "public",
];

if (process.argv.includes("--dry-run")) {
  console.log(`${command} ${args.join(" ")} > ${outputPath}`);
  process.exit(0);
}

try {
  const generatedTypes = execFileSync(command, args, {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
  });

  mkdirSync(path.dirname(outputPath), { recursive: true });
  writeFileSync(
    outputPath,
    `// Generated by npm run db:types. Do not edit manually.\n\n${generatedTypes}`,
  );

  console.log(`Generated Supabase database types at ${path.relative(process.cwd(), outputPath)}.`);
} catch (error) {
  console.error(
    "Failed to generate Supabase database types. Confirm Supabase CLI access with `supabase login` or SUPABASE_ACCESS_TOKEN.",
  );
  process.exit(error.status || 1);
}
